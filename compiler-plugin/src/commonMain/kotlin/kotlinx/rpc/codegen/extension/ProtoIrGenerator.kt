internal class ProtoDeclaration(
    val message: IrClass,
    val messageInternal: IrClass,
    val descriptor: IrClass,
    val marshaller: IrClass,
)

/**
 * Generates IR additionally to the Kotlin source code generated by `protoc-gen` plugin.
 *
 * First, it generates the `@WithProtoDescriptor(MyMessageInternal.DESCRIPTOR::class)` annotation for the
 * message interface. The proto-gen plugin generates the actual descriptor as part of the internal message class,
 * similar to MARSHALLER.
 * ```
 * class MyMessageInternal : MyMessage {
 *     @InternalRpcApi
 *     public object DESCRIPTOR: ProtoDescriptor<MyMessage> = ...
 * }
 * ```
 *
 * Additionally, it generates the implementation of the `invoke` operation function on the
 * generated `MyMessage.Companion` object in [implementInvokeFunction].
 */
internal class ProtoIrGenerator(
    private val declaration: ProtoDeclaration,
    private val ctx: RpcIrContext,
    @Suppress("unused")
    private val logger: MessageCollector,
) {

    fun generate() {
        addWithProtoDescriptorAnnotation()
        addWithGrpcMarshallerAnnotation()
        addSubclassOptInRequiredAnnotation()

        declaration.message.companionObject()?.apply {
            generateCompanionObjectConstructor(ctx.pluginContext)
            implementInvokeFunction(this)
        }
    }

    /**
     * Add the @WithProtoDescriptor annotation to the message interface.
     * This is used by `protoDescriptorOf()` to get the descriptor.
     * The java implementation uses reflection to find the descriptor object.
     *
     * ```
     * @WithProtoDescriptor(MyMessageInternal.DESCRIPTOR::class)
     * interface MyMessage {}
     * ```
     */
    private fun addWithProtoDescriptorAnnotation() {
        addWithSomethingAnnotation(ctx.withProtoDescriptor, ProtoDeclaration::descriptor)
    }

    /**
     * Add the @WithGrpcMarshaller annotation to the message interface.
     * This is used by `grpcMarshallerOf()` to get the GrpcMarshaller object.
     * The java implementation uses reflection to find the descriptor object.
     *
     * ```
     * @WithGrpcMarshaller(MyMessageInternal.MARSHALLER::class)
     * interface MyMessage {}
     * ```
     */
    private fun addWithGrpcMarshallerAnnotation() {
        addWithSomethingAnnotation(ctx.withGrpcMarshallerAnnotation, ProtoDeclaration::marshaller)
    }

    /**
     * Add the @SubclassOptInRequired(ProtobufMessagesInheritance::class) annotation
     * to the message interface. Uses [IrPluginContext.metadataDeclarationRegistrar]
     * so the annotation is serialized into metadata and visible to downstream modules.
     */
    private fun addSubclassOptInRequiredAnnotation() {
        val message = declaration.message
        val annotationSymbol = ctx.subclassOptInRequired
        val markerClass = ctx.protobufMessagesInheritance

        val annotation = irBuilder(ctx.pluginContext, message.symbol)
            .irAnnotation(annotationSymbol.constructors.single())
            .apply {
                val markerType = markerClass.defaultType
                arguments {
                    values {
                        +IrVarargImpl(
                            startOffset = message.startOffset,
                            endOffset = message.endOffset,
                            type = ctx.irBuiltIns.arrayClass.typeWith(
                                ctx.irBuiltIns.kClassClass.typeWith(ctx.irBuiltIns.annotationType)
                            ),
                            varargElementType = ctx.irBuiltIns.kClassClass.typeWith(ctx.irBuiltIns.annotationType),
                            elements = listOf(
                                IrClassReferenceImpl(
                                    startOffset = message.startOffset,
                                    endOffset = message.endOffset,
                                    type = ctx.irBuiltIns.kClassClass.typeWith(markerType),
                                    symbol = markerClass,
                                    classType = markerType,
                                )
                            ),
                        )
                    }
                }
            }

        ctx.pluginContext.metadataDeclarationRegistrar.addMetadataVisibleAnnotationsToElement(
            declaration = message,
            annotations = listOf(annotation),
        )
    }

    /**
     * Add the @With<Something> annotation to the message interface.
     *
     * ```
     * @With<Something>(MyMessageInternal.<SOMETHING>::class)
     * interface MyMessage {}
     * ```
     */
    private fun addWithSomethingAnnotation(
        withSomethingAnnotation: IrClassSymbol,
        somethingClass: ProtoDeclaration.() -> IrClass,
    ) {
        val message = declaration.message

        val annotation = irBuilder(ctx.pluginContext, message.symbol)
            .irAnnotation(withSomethingAnnotation.constructors.single())
            .apply {
                val clazz = declaration.somethingClass()
                val descriptorObjectType = clazz.defaultType
                arguments {
                    values {
                        +IrClassReferenceImpl(
                            startOffset = startOffset,
                            endOffset = endOffset,
                            type = ctx.irBuiltIns.kClassClass.typeWith(descriptorObjectType),
                            symbol = clazz.symbol,
                            classType = descriptorObjectType,
                        )
                    }
                }
            }

        message.annotations += annotation
    }

    /**
     * ```kotlin
     * companion object {
     *     public operator fun invoke(
     *         body: <message-name>.Builder.() -> Unit,
     *     ): <message-name> {
     *         val message = <message-name>Internal()
     *         body(message)
     *         message.checkRequiredFields()
     *         return message
     *     }
     * }
     * ```
     */
    private fun implementInvokeFunction(companionObject: IrClass) {
        val invokeFunction = companionObject.simpleFunctions().find { it.name == ProtoNames.INVOKE_NAME }
            ?: error("Expected `invoke` function to be present in ${companionObject.kotlinFqName}. " +
                "FIR failed to do so.")

        invokeFunction.body = irBuilder(ctx.pluginContext, invokeFunction.symbol)
            .irBlockBody {
                val internalConstructorSymbol = declaration.messageInternal.constructors.find {
                    it.parameters.isEmpty()
                }?.symbol ?: error("Internal message class has no constructor without parameters.")

                val messageVar = irTemporary(
                    value = irCallConstructor(internalConstructorSymbol, listOf()),
                    nameHint = "message",
                )

                val bodyParameter = invokeFunction.parameters
                    .single { it.kind == IrParameterKind.Regular }
                val bodyInvokeMethod = bodyParameter.type.classOrNull?.owner?.functions
                    ?.find { it.name.identifier == "invoke" }
                    ?: error("Unable to resolve invoke method on companion object's invoke parameter.")

                // `body(message)` is actually `body.invoke(message)`
                +irCall(bodyInvokeMethod.symbol, type = ctx.irBuiltIns.unitType).apply {
                    arguments[0] = irGet(bodyParameter)
                    arguments[1] = irGet(messageVar)
                }

                // call message.checkRequiredFields()
                val checkRequiredFieldsMethod = declaration.messageInternal.functions
                    .find { it.name == ProtoNames.INTERNAL_CHECK_REQUIRED_FIELDS_NAME }
                if (checkRequiredFieldsMethod != null) {
                    // Only proto2 message actually have a checkRequiredFieldsMethod to call.
                    +irCall(checkRequiredFieldsMethod).apply {
                        dispatchReceiver = irGet(messageVar)
                    }
                }
                +irReturn(irGet(messageVar))
            }
    }
}
